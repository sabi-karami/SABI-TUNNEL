def load_json(path: Path, default):
    try:
        return json.loads(path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return default


def save_json(path: Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False))
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def rand_password(n=20):
    return "".join(secrets.choice(ALPHABET) for _ in range(n))


def hash_password(pw: str, salt: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt), 200_000).hex()


class State:
    def __init__(self):
        self.cfg = load_json(CONFIG_PATH, {})
        self.users = load_json(USERS_PATH, {})
        self.stats = load_json(STATS_PATH, {"months": {}, "prev": {}})
        self.history = []
        self.live = {}
        self.endpoint_ok = False
        self.last_poll = 0.0
        self.failed_logins = []
        self.lock = asyncio.Lock()
        self.version = ""

    def save(self):
        save_json(USERS_PATH, self.users)
        save_json(STATS_PATH, self.stats)


