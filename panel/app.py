@app.post("/api/login")
async def login(body: LoginIn):
    now = time.time()
    S.failed_logins = [t for t in S.failed_logins if now - t < 300]
    if len(S.failed_logins) >= 8:
        raise HTTPException(429, "تلاش زیاد؛ ۵ دقیقه صبر کنید")
    ok = (hmac.compare_digest(body.username, S.cfg.get("admin_user", "admin")) and
          hmac.compare_digest(hash_password(body.password, S.cfg["admin_salt"]), S.cfg["admin_hash"]))
    if not ok:
        S.failed_logins.append(now)
        await asyncio.sleep(1)
        raise HTTPException(401, "نام کاربری یا رمز اشتباه است")
    resp = JSONResponse({"ok": True})
    resp.set_cookie("ttp", make_token(), max_age=SESSION_TTL, httponly=True,
                    secure=True, samesite="strict")
    return resp


