class HeaderBodyMiddleware:
    """TrustTunnel v1.1 reverse proxy does not forward request bodies.
    The UI therefore sends JSON as base64 in the X-Body header; we restore it here."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] == "http":
            raw = next((v for k, v in scope["headers"] if k == b"x-body"), None)
            if raw:
                import base64
                try:
                    body = base64.b64decode(raw + b"=" * (-len(raw) % 4))
                except Exception:
                    body = b""
                hdrs = [(k, v) for k, v in scope["headers"]
                        if k not in (b"x-body", b"content-length", b"content-type")]
                hdrs += [(b"content-type", b"application/json"), (b"content-length", str(len(body)).encode())]
                scope = dict(scope, headers=hdrs)
                done = False

                async def receive2():
                    nonlocal done
                    if not done:
                        done = True
                        return {"type": "http.request", "body": body, "more_body": False}
                    return await receive()

                return await self.app(scope, receive2, send)
        await self.app(scope, receive, send)


app.add_middleware(HeaderBodyMiddleware)


