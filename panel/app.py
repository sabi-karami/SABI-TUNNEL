def sysinfo():
    info = {}
    try:
        info["load"] = os.getloadavg()[0]
        info["cpus"] = os.cpu_count()
        mem = {}
        for line in Path("/proc/meminfo").read_text().splitlines():
            k, v = line.split(":", 1)
            mem[k] = int(v.split()[0]) * 1024
        info["mem_total"] = mem["MemTotal"]
        info["mem_used"] = mem["MemTotal"] - mem["MemAvailable"]
        info["uptime"] = float(Path("/proc/uptime").read_text().split()[0])
        du = shutil.disk_usage("/")
        info["disk_total"], info["disk_used"] = du.total, du.used
    except Exception:
        pass
    return info


def cert_expiry():
    host = S.cfg.get("tt_host", "")
    try:
        out = subprocess.run(["openssl", "x509", "-enddate", "-noout", "-in",
                              f"/etc/letsencrypt/live/{host}/cert.pem"],
                             capture_output=True, text=True, timeout=5).stdout
        t = time.strptime(out.strip().split("=", 1)[1], "%b %d %H:%M:%S %Y %Z")
        return int(time.mktime(t))
    except Exception:
        return None


