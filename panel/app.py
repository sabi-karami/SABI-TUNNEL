def cli():
    ap = argparse.ArgumentParser(prog="ttpanel")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init", help="create/refresh panel config and credentials")
    p.add_argument("--tt-host", required=True)
    p.add_argument("--panel-host", required=True)
    p.add_argument("--ipv4", default="")
    p.add_argument("--ipv6", default="")
    p.add_argument("--region", default="")
    p.add_argument("--server-name", default="")
    p.add_argument("--first-user", default="me")
    p.add_argument("--admin-password", default="")
    p2 = sub.add_parser("link", help="print a user's tt:// link")
    p2.add_argument("user")
    p2.add_argument("--protocol", default="http2")
    p2.add_argument("--addr", default="dual")
    p3 = sub.add_parser("reset-admin", help="set a new random admin password")
    args = ap.parse_args()

    if args.cmd == "init":
        cfg = S.cfg
        created_pw = None
        if "admin_hash" not in cfg or args.admin_password:
            created_pw = args.admin_password or rand_password(18)
            cfg["admin_user"] = "admin"
            cfg["admin_salt"] = secrets.token_hex(16)
            cfg["admin_hash"] = hash_password(created_pw, cfg["admin_salt"])
        cfg.setdefault("secret", secrets.token_hex(32))
        cfg.setdefault("system_password", rand_password(32))
        cfg.setdefault("session_epoch", 0)
        cfg.setdefault("dns_upstreams", ["1.1.1.1", "8.8.8.8"])
        cfg["tt_host"], cfg["panel_host"] = args.tt_host, args.panel_host
        cfg["ipv4"], cfg["ipv6"], cfg["region"] = args.ipv4, args.ipv6, args.region
        if args.server_name or "server_name" not in cfg:
            cfg["server_name"] = args.server_name or "TrustTunnel"
        save_json(CONFIG_PATH, cfg)
        if not S.users:
            S.users[args.first_user] = new_user("کاربر اول")
        S.save()
        write_credentials()
        if created_pw:
            print(f"ADMIN_PASSWORD={created_pw}")
    elif args.cmd == "link":
        print(build_link(args.user, args.protocol, args.addr))
    elif args.cmd == "reset-admin":
        pw = rand_password(18)
        S.cfg["admin_salt"] = secrets.token_hex(16)
        S.cfg["admin_hash"] = hash_password(pw, S.cfg["admin_salt"])
        S.cfg["session_epoch"] = S.cfg.get("session_epoch", 0) + 1
        save_json(CONFIG_PATH, S.cfg)
        print(f"ADMIN_PASSWORD={pw}")


if __name__ == "__main__":
    cli()
