class PasswordIn(BaseModel):
    old: str
    new: str


@app.post("/api/admin/password")
async def change_password(request: Request, body: PasswordIn):
    require_auth(request)
    if not hmac.compare_digest(hash_password(body.old, S.cfg["admin_salt"]), S.cfg["admin_hash"]):
        raise HTTPException(400, "رمز فعلی اشتباه است")
    if len(body.new) < 10:
        raise HTTPException(400, "رمز جدید باید حداقل ۱۰ کاراکتر باشد")
    S.cfg["admin_salt"] = secrets.token_hex(16)
    S.cfg["admin_hash"] = hash_password(body.new, S.cfg["admin_salt"])
    S.cfg["session_epoch"] = S.cfg.get("session_epoch", 0) + 1
    save_json(CONFIG_PATH, S.cfg)
    resp = JSONResponse({"ok": True})
    resp.set_cookie("ttp", make_token(), max_age=SESSION_TTL, httponly=True,
                    secure=True, samesite="strict")
    return resp


class SettingsIn(BaseModel):
    server_name: str | None = None
    dns_upstreams: list[str] | None = None


@app.post("/api/admin/settings")
async def update_settings(request: Request, body: SettingsIn):
    require_auth(request)
    if body.server_name is not None:
        S.cfg["server_name"] = body.server_name.strip()[:40] or "TrustTunnel"
    if body.dns_upstreams is not None:
        S.cfg["dns_upstreams"] = [d.strip() for d in body.dns_upstreams if d.strip()][:6]
    save_json(CONFIG_PATH, S.cfg)
    return {"ok": True}


@app.post("/api/admin/restart")
async def restart_endpoint(request: Request):
    require_auth(request)
    async with S.lock:
        await apply_changes()
    return {"ok": True}


