def make_token():
    exp = int(time.time()) + SESSION_TTL
    msg = f"{exp}.{S.cfg.get('session_epoch', 0)}"
    sig = hmac.new(bytes.fromhex(S.cfg["secret"]), msg.encode(), "sha256").hexdigest()
    return f"{msg}.{sig}"


def token_valid(tok: str) -> bool:
    try:
        exp, epoch, sig = tok.split(".")
        msg = f"{exp}.{epoch}"
        good = hmac.new(bytes.fromhex(S.cfg["secret"]), msg.encode(), "sha256").hexdigest()
        return (hmac.compare_digest(good, sig) and int(exp) > time.time()
                and int(epoch) == S.cfg.get("session_epoch", 0))
    except Exception:
        return False


def require_auth(request: Request):
    if not token_valid(request.cookies.get("ttp", "")):
        raise HTTPException(401, "unauthorized")


@app.middleware("http")
async def security_headers(request: Request, call_next):
    resp = await call_next(request)
    resp.headers["X-Frame-Options"] = "DENY"
    resp.headers["X-Content-Type-Options"] = "nosniff"
    resp.headers["Referrer-Policy"] = "no-referrer"
    if request.url.path.startswith("/assets/") and resp.status_code == 200:
        resp.headers["Cache-Control"] = "public, max-age=604800, immutable"
    else:
        resp.headers["Cache-Control"] = "no-store"
    return resp


