def write_credentials():
    lines = ["# Generated by TrustTunnel Panel. Manage users in the panel, not here.", ""]
    lines += ["[[client]]", f"username = {json.dumps(SYSTEM_USER)}",
              f"password = {json.dumps(S.cfg['system_password'])}", ""]
    for name, u in sorted(S.users.items()):
        if u.get("enabled"):
            lines += ["[[client]]", f"username = {json.dumps(name)}",
                      f"password = {json.dumps(u['password'])}", ""]
    path = TT_DIR / "credentials.toml"
    tmp = path.with_suffix(".tmp")
    tmp.write_text("\n".join(lines))
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def fetch_clients():
    with urllib.request.urlopen(METRICS_URL + "/clients", timeout=3) as r:
        return json.load(r)


async def run(*cmd):
    try:
        proc = await asyncio.create_subprocess_exec(
            *cmd, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.STDOUT)
    except FileNotFoundError as e:
        return 127, str(e)
    out, _ = await proc.communicate()
    return proc.returncode, out.decode(errors="replace").strip()


async def poll_once():
    try:
        data = await asyncio.to_thread(fetch_clients)
    except Exception:
        S.endpoint_ok = False
        return
    now = time.time()
    prev = S.stats.setdefault("prev", {})
    month = time.strftime("%Y-%m", time.gmtime())
    m = S.stats.setdefault("months", {}).setdefault(month, {"in": 0, "out": 0})
    tot_in = tot_out = sessions = 0
    live = {}
    for c in data:
        name = c.get("username")
        cin, cout = int(c.get("inbound") or 0), int(c.get("outbound") or 0)
        p = prev.get(name, {"in": 0, "out": 0})
        din = cin - p["in"] if cin >= p["in"] else cin
        dout = cout - p["out"] if cout >= p["out"] else cout
        prev[name] = {"in": cin, "out": cout}
        tot_in += din
        tot_out += dout
        sess = int(c.get("sessions") or 0)
        sessions += sess
        live[name] = {"sessions": sess, "ip": c.get("ip")}
        u = S.users.get(name)
        if u is not None:
            u["used_in"] = u.get("used_in", 0) + din
            u["used_out"] = u.get("used_out", 0) + dout
            if sess:
                u["last_seen"] = int(now)
                if c.get("ip"):
                    u["last_ip"] = c["ip"]
    m["in"] += tot_in
    m["out"] += tot_out
    dt = max(now - S.last_poll, 1) if S.last_poll else POLL_SECONDS
    S.history.append([int(now), round(tot_in / dt), round(tot_out / dt), sessions])
    del S.history[:-HISTORY_POINTS]
    S.last_poll = now
    S.live = live
    S.endpoint_ok = True


_restart_task = None


async def _delayed_restart(delay):
    # The panel itself is reached through the endpoint's reverse proxy, so the HTTP
    # response must leave before the endpoint restarts; otherwise it is lost.
    await asyncio.sleep(delay)
    async with S.lock:
        try:
            await poll_once()
        except Exception:
            pass
        write_credentials()
        await run("systemctl", "restart", "trusttunnel")
        S.stats["prev"] = {}
        S.last_poll = 0.0
        S.save()


async def apply_changes(delay=1.5):
    """Regenerate credentials.toml and restart the endpoint (credentials are not hot-reloaded).
    The restart is deferred and debounced so the API response reaches the browser first."""
    global _restart_task
    write_credentials()
    S.save()
    if _restart_task is None or _restart_task.done():
        _restart_task = asyncio.create_task(_delayed_restart(delay))


async def enforce_limits():
    changed = False
    now = time.time()
    for u in S.users.values():
        if not u.get("enabled"):
            continue
        reason = None
        quota = u.get("quota_gb") or 0
        if quota and u.get("used_in", 0) + u.get("used_out", 0) >= quota * 10**9:
            reason = "quota"
        if u.get("expires") and now > u["expires"]:
            reason = "expired"
        if reason:
            u["enabled"] = False
            u["disabled_reason"] = reason
            changed = True
    if changed:
        await apply_changes()


async def background_loop():
    while True:
        try:
            async with S.lock:
                await poll_once()
                await enforce_limits()
                S.save()
        except Exception as e:
            print("poll error:", e, file=sys.stderr)
        await asyncio.sleep(POLL_SECONDS)


