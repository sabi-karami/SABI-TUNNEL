def new_user(note="", quota_gb=0, days=0):
    now = int(time.time())
    return {"password": rand_password(), "enabled": True, "note": note[:200],
            "quota_gb": max(quota_gb, 0), "expires": now + days * 86400 if days > 0 else 0,
            "created": now, "used_in": 0, "used_out": 0}


@app.post("/api/users")
async def create_user(request: Request, body: UserIn):
    require_auth(request)
    name = body.name.strip() or f"user{secrets.randbelow(9000) + 1000}"
    if not USERNAME_RE.match(name) or name.startswith("_"):
        raise HTTPException(400, "نام کاربری: فقط حروف انگلیسی، عدد و . _ - (۲ تا ۳۲ کاراکتر)")
    async with S.lock:
        if name in S.users:
            raise HTTPException(409, "این نام کاربری وجود دارد")
        S.users[name] = new_user(body.note, body.quota_gb, body.days)
        await apply_changes()
    return user_view(name, S.users[name])


class UserPatch(BaseModel):
    enabled: bool | None = None
    note: str | None = None
    quota_gb: float | None = None
    add_days: int | None = None
    clear_expiry: bool = False
    reset_usage: bool = False
    regen_password: bool = False


@app.patch("/api/users/{name}")
async def update_user(request: Request, name: str, body: UserPatch):
    require_auth(request)
    async with S.lock:
        u = S.users.get(name)
        if not u:
            raise HTTPException(404, "not found")
        restart = False
        if body.note is not None:
            u["note"] = body.note[:200]
        if body.quota_gb is not None:
            u["quota_gb"] = max(body.quota_gb, 0)
        if body.add_days:
            base = max(u.get("expires") or 0, time.time())
            u["expires"] = int(base + body.add_days * 86400)
        if body.clear_expiry:
            u["expires"] = 0
        if body.reset_usage:
            u["used_in"] = u["used_out"] = 0
        if body.regen_password:
            u["password"] = rand_password()
            restart = True
        if body.enabled is not None and body.enabled != u.get("enabled"):
            u["enabled"] = body.enabled
            u.pop("disabled_reason", None)
            restart = True
        if restart:
            await apply_changes()
        else:
            S.save()
    return user_view(name, u)


@app.delete("/api/users/{name}")
async def delete_user(request: Request, name: str):
    require_auth(request)
    async with S.lock:
        if S.users.pop(name, None) is None:
            raise HTTPException(404, "not found")
        await apply_changes()
    return {"ok": True}


def build_link(name, protocol="http2", addr="dual"):
    u = S.users[name]
    cfg = S.cfg
    addrs = []
    if addr in ("dual", "v4") and cfg.get("ipv4"):
        addrs.append(f"{cfg['ipv4']}:443")
    if addr in ("dual", "v6") and cfg.get("ipv6"):
        addrs.append(f"[{cfg['ipv6']}]:443")
    if addr == "domain" or not addrs:
        addrs = [f"{cfg['tt_host']}:443"]
    label = f"{cfg.get('server_name', 'TrustTunnel')} · {name}"
    if protocol == "http3":
        label += " · QUIC"
    return make_deeplink(cfg["tt_host"], addrs, name, u["password"], name=label,
                         dns_upstreams=cfg.get("dns_upstreams"), protocol=protocol)


@app.get("/api/users/{name}/link")
async def user_link(request: Request, name: str, protocol: str = "http2", addr: str = "dual"):
    require_auth(request)
    if name not in S.users:
        raise HTTPException(404, "not found")
    link = build_link(name, "http3" if protocol == "http3" else "http2", addr)
    img = qrcode.make(link, image_factory=qrcode.image.svg.SvgPathImage, box_size=8, border=2)
    return {"link": link, "qr_svg": img.to_string(encoding="unicode"), "share_url": share_url(name)}


# ---------------------------------------------------------------- public share page (per user)
# /s/<name>/<token>: QR, "add to app" button, usage and download links for the end user.
# The token is derived from the user's password, so "new password" also revokes the page.

def share_token(name: str) -> str:
    u = S.users[name]
    msg = f"share:{name}:{u['password']}".encode()
    return hmac.new(bytes.fromhex(S.cfg["secret"]), msg, "sha256").hexdigest()[:24]


def share_url(name: str) -> str:
    host = S.cfg.get("panel_host") or S.cfg.get("tt_host")
    return f"https://{host}/s/{name}/{share_token(name)}"


def _share_user(name: str, token: str):
    if name == SYSTEM_USER or name not in S.users or not re.fullmatch(r"[0-9a-f]{24}", token or ""):
        raise HTTPException(404, "not found")
    if not hmac.compare_digest(share_token(name), token):
        raise HTTPException(404, "not found")
    return S.users[name]


def _fmt_bytes(b: float) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if b < 1024 or unit == "TB":
            return f"{b:.0f} {unit}" if unit in ("B", "KB") else f"{b:.1f} {unit}"
        b /= 1024
    return ""


