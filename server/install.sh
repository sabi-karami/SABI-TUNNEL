#!/usr/bin/env bash
# TrustTunnel Stack - server installer (Ubuntu 22.04/24.04, x86_64 or arm64).
# Idempotent: safe to run again to update configs, the endpoint or the panel.
#
#   sudo TT_HOST=tt.example.com PANEL_HOST=panel.example.com ./server/install.sh
set -euo pipefail

TT_HOST="${TT_HOST:?set TT_HOST, e.g. tt.example.com}"
PANEL_HOST="${PANEL_HOST:?set PANEL_HOST, e.g. panel.example.com}"
TT_VERSION="${TT_VERSION:-1.1.0}"
SERVER_NAME="${SERVER_NAME:-TrustTunnel}"
REGION="${REGION:-}"
FIRST_USER="${FIRST_USER:-me}"
ACME_EMAIL="${ACME_EMAIL:-}"
SRC="$(cd "$(dirname "$0")/.." && pwd)"
TT_DIR=/opt/trusttunnel
PANEL_DIR=/opt/ttpanel
log() { printf '\033[1;36m[tt-stack]\033[0m %s\n' "$*"; }

[ "$(id -u)" -eq 0 ] || { echo "run as root"; exit 1; }
export DEBIAN_FRONTEND=noninteractive

log "Installing packages"
apt-get update -y -q
apt-get install -y -q curl ca-certificates certbot python3-venv openssl iproute2 >/dev/null

log "Swap + kernel network tuning (BBR, fq, big UDP buffers for QUIC)"
if ! swapon --show | grep -q /swapfile; then
  fallocate -l 1G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi
cat > /etc/sysctl.d/90-trusttunnel.conf <<SYS
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
net.core.rmem_default = 2097152
net.core.wmem_default = 2097152
net.ipv4.tcp_rmem = 4096 131072 16777216
net.ipv4.tcp_wmem = 4096 65536 16777216
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_slow_start_after_idle = 0
net.core.somaxconn = 4096
fs.file-max = 1048576
vm.swappiness = 10
SYS
sysctl --system >/dev/null

log "Installing TrustTunnel endpoint v${TT_VERSION}"
if ! "$TT_DIR/trusttunnel_endpoint" --version 2>/dev/null | grep -q "$TT_VERSION"; then
  systemctl stop trusttunnel 2>/dev/null || true
  curl -fsSL https://raw.githubusercontent.com/TrustTunnel/TrustTunnel/refs/heads/master/scripts/install.sh \
    | sh -s - -V "$TT_VERSION" -o "$TT_DIR"
fi
"$TT_DIR/trusttunnel_endpoint" --version

log "Detecting public addresses"
IPV4="$(curl -4 -fsS --max-time 10 https://checkip.amazonaws.com || true)"
IPV6="$(ip -6 addr show scope global | awk '/inet6/{print $2}' | cut -d/ -f1 | head -n1 || true)"
IFACE="$(ip -o route get 1.1.1.1 | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')"
log "IPv4=${IPV4:-none} IPv6=${IPV6:-none} iface=${IFACE}"

log "Waiting for DNS of ${TT_HOST} and ${PANEL_HOST} to point at this server"
for h in "$TT_HOST" "$PANEL_HOST"; do
  for i in $(seq 1 60); do
    got="$(getent ahostsv4 "$h" | awk '{print $1; exit}' || true)"
    [ -n "$IPV4" ] && [ "$got" = "$IPV4" ] && break
    [ -z "$IPV4" ] && [ -n "$got" ] && break
    sleep 5
  done
done

LIVE="/etc/letsencrypt/live/${TT_HOST}"
if [ ! -f "$LIVE/fullchain.pem" ] || ! openssl x509 -in "$LIVE/fullchain.pem" -noout -text | grep -q "DNS:${PANEL_HOST}"; then
  log "Issuing Let's Encrypt certificate (HTTP-01 on port 80)"
  systemctl stop trusttunnel 2>/dev/null || true
  if [ -n "$ACME_EMAIL" ]; then EMAIL_ARGS=(-m "$ACME_EMAIL"); else EMAIL_ARGS=(--register-unsafely-without-email); fi
  certbot certonly --standalone --non-interactive --agree-tos "${EMAIL_ARGS[@]}" \
    --cert-name "$TT_HOST" -d "$TT_HOST" -d "$PANEL_HOST" --expand
fi
mkdir -p /etc/letsencrypt/renewal-hooks/deploy
cat > /etc/letsencrypt/renewal-hooks/deploy/trusttunnel-reload.sh <<'HOOK'
#!/bin/sh
systemctl reload trusttunnel || systemctl restart trusttunnel
HOOK
chmod +x /etc/letsencrypt/renewal-hooks/deploy/trusttunnel-reload.sh

log "Writing endpoint configuration"
PROXY_MASK_FILE="$TT_DIR/.proxy_mask"
[ -f "$PROXY_MASK_FILE" ] || echo "/_$(openssl rand -hex 12)" > "$PROXY_MASK_FILE"
PROXY_MASK="$(cat "$PROXY_MASK_FILE")"
LISTEN="0.0.0.0:443"; [ -n "$IPV6" ] && LISTEN="[::]:443"
cat > "$TT_DIR/vpn.toml" <<VPN
# Generated by TrustTunnel Stack (server/install.sh)
listen_address = "${LISTEN}"
ipv6_available = $([ -n "$IPV6" ] && echo true || echo false)
allow_private_network_connections = false
tls_handshake_timeout_secs = 10
client_listener_timeout_secs = 600
connection_establishment_timeout_secs = 30
tcp_connections_timeout_secs = 604800
udp_connections_timeout_secs = 300
credentials_file = "credentials.toml"

[listen_protocols]

[listen_protocols.http1]
upload_buffer_size = 32768

[listen_protocols.http2]
initial_connection_window_size = 8388608
initial_stream_window_size = 131072
max_concurrent_streams = 1000
max_frame_size = 16384
header_table_size = 65536

[listen_protocols.quic]
recv_udp_payload_size = 1350
send_udp_payload_size = 1350
initial_max_data = 104857600
initial_max_stream_data_bidi_local = 1048576
initial_max_stream_data_bidi_remote = 1048576
initial_max_stream_data_uni = 1048576
initial_max_streams_bidi = 4096
initial_max_streams_uni = 4096
max_connection_window = 25165824
max_stream_window = 16777216
disable_active_migration = true
enable_early_data = true
message_queue_capacity = 4096

[forward_protocol]
direct = {}

# The admin panel is served on PANEL_HOST through the endpoint itself (same port 443).
[reverse_proxy]
server_address = "127.0.0.1:8080"
path_mask = "${PROXY_MASK}"
h3_backward_compatibility = false

[icmp]
interface_name = "${IFACE}"
request_timeout_secs = 3
recv_message_queue_capacity = 256

[metrics]
address = "127.0.0.1:1987"
request_timeout_secs = 3
per_client_metrics = true
VPN
cat > "$TT_DIR/hosts.toml" <<HOSTS
[[main_hosts]]
hostname = "${TT_HOST}"
cert_chain_path = "${LIVE}/fullchain.pem"
private_key_path = "${LIVE}/privkey.pem"

[[reverse_proxy_hosts]]
hostname = "${PANEL_HOST}"
cert_chain_path = "${LIVE}/fullchain.pem"
private_key_path = "${LIVE}/privkey.pem"
HOSTS

log "Installing panel"
mkdir -p "$PANEL_DIR" /etc/ttpanel /var/lib/ttpanel
cp "$SRC"/panel/*.py "$SRC"/panel/index.html "$SRC"/panel/requirements.txt "$PANEL_DIR"/
[ -x "$PANEL_DIR/venv/bin/python" ] || python3 -m venv "$PANEL_DIR/venv"
"$PANEL_DIR/venv/bin/pip" install -q --upgrade pip
"$PANEL_DIR/venv/bin/pip" install -q -r "$PANEL_DIR/requirements.txt"
chmod 700 /etc/ttpanel /var/lib/ttpanel
INIT_OUT="$(cd "$PANEL_DIR" && ./venv/bin/python app.py init --tt-host "$TT_HOST" --panel-host "$PANEL_HOST" \
  --ipv4 "$IPV4" --ipv6 "$IPV6" --region "$REGION" --server-name "$SERVER_NAME" --first-user "$FIRST_USER")"
if echo "$INIT_OUT" | grep -q ADMIN_PASSWORD; then
  echo "$INIT_OUT" | grep ADMIN_PASSWORD | sed 's/^/panel_/' > /root/ttpanel-admin.txt
  echo "panel_url=https://${PANEL_HOST}/" >> /root/ttpanel-admin.txt
  chmod 600 /root/ttpanel-admin.txt
fi

log "Installing systemd services"
cat > /etc/systemd/system/trusttunnel.service <<UNIT
[Unit]
Description=TrustTunnel endpoint
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=${TT_DIR}
ExecStart=${TT_DIR}/trusttunnel_endpoint vpn.toml hosts.toml
ExecReload=/bin/kill -HUP \$MAINPID
Restart=always
RestartSec=2
LimitNOFILE=1048576

[Install]
WantedBy=multi-user.target
UNIT
cat > /etc/systemd/system/ttpanel.service <<UNIT
[Unit]
Description=TrustTunnel Panel
After=network-online.target trusttunnel.service

[Service]
Type=simple
WorkingDirectory=${PANEL_DIR}
ExecStart=${PANEL_DIR}/venv/bin/uvicorn app:app --host 127.0.0.1 --port 8080 --no-server-header --log-level warning --timeout-graceful-shutdown 3 --timeout-keep-alive 30
TimeoutStopSec=10
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable -q trusttunnel ttpanel
systemctl restart trusttunnel
systemctl restart ttpanel
sleep 3
systemctl is-active trusttunnel ttpanel

log "Done."
log "Panel:   https://${PANEL_HOST}/   (admin password in /root/ttpanel-admin.txt)"
log "First user link:"
(cd "$PANEL_DIR" && ./venv/bin/python app.py link "$FIRST_USER")
